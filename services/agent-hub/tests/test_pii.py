from __future__ import annotations

from nexusflow_agents.core.pii import PIIShield


def test_mask_session_replaces_supported_pii_with_stable_tokens() -> None:
    session = PIIShield(enabled=True).session()
    text = (
        "联系 alice@example.com 或 13800138000，"
        "身份证 110101199001011234，卡号 6222 0202 0000 1234，IP 10.0.0.8。"
        "再次联系 alice@example.com。"
    )
    masked = session.mask(text)

    assert "alice@example.com" not in masked
    assert "13800138000" not in masked
    assert "110101199001011234" not in masked
    assert "10.0.0.8" not in masked
    assert masked.count("{{EMAIL_1}}") == 2
    assert session.counts() == {
        "email": 1,
        "id_card": 1,
        "bank_card": 1,
        "phone": 1,
        "ipv4": 1,
    }
    assert session.total() == 5


def test_mask_session_restores_and_masks_output() -> None:
    shield = PIIShield(enabled=True, restore_output=True)
    session = shield.session()
    masked = session.mask("mail me at bob@example.com")
    assert session.output(masked) == "mail me at bob@example.com"

    keep_masked = PIIShield(enabled=True, restore_output=False).session()
    masked = keep_masked.mask("call 13800138000")
    assert keep_masked.output(masked) == "call {{PHONE_1}}"
    # PII generated by the model itself is also masked on the way out.
    assert keep_masked.output("new address 10.1.2.3") == "new address {{IPV4_1}}"


def test_disabled_shield_is_a_noop() -> None:
    session = PIIShield(enabled=False).session()
    text = "alice@example.com 13800138000"
    assert session.mask(text) == text
    assert session.total() == 0
    assert session.output(text) == text


def test_detect_counts_without_tokens() -> None:
    shield = PIIShield(enabled=True)
    assert shield.detect("a@b.com 1.2.3.4") == {"email": 1, "ipv4": 1}
